import {build} from 'esbuild';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
await writeFile('src/studio-importer.mjs','// Generated by scripts/build.mjs from static/StudioCaptureImporter.luau.\nexport const STUDIO_IMPORTER='+JSON.stringify(await readFile('static/StudioCaptureImporter.luau','utf8'))+';\n');
await mkdir('dist',{recursive:true});
const bundle=await build({entryPoints:['src/stdio.mjs'],bundle:true,platform:'node',target:'node22',format:'esm',outfile:'dist/dex-mcp.mjs',minify:true,sourcemap:false,metafile:true,banner:{js:"import{createRequire as __dexCreateRequire}from'node:module';const require=__dexCreateRequire(import.meta.url);"}});
const packages=new Set();
for(const input of Object.keys(bundle.metafile.inputs)){
 const match=input.replaceAll('\\','/').match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);if(match)packages.add(match[1]);
}
let notices='Third-party packages included in dex-mcp.mjs\n\n';
for(const name of [...packages].sort()){
 const metadata=JSON.parse(await readFile('node_modules/'+name+'/package.json','utf8'));
 notices+=`${name} ${metadata.version} (${metadata.license||'see license'})\n`;
 let license;for(const filename of ['LICENSE','LICENSE.md','LICENSE.txt','license','COPYING'])try{license=await readFile('node_modules/'+name+'/'+filename,'utf8');break;}catch{}
 if(!license)throw new Error('Missing distribution license for '+name);
 notices+=license+'\n\n';
}
notices+='\nExecutor MCP for Roblox\n'+await readFile('third-party/executor-mcp/LICENSE','utf8');
await writeFile('dist/THIRD_PARTY_NOTICES.txt',notices);
await writeFile('dist/README.txt','Dex MCP server\nRequires Node.js 22 or newer.\nConfigure an MCP stdio server with command: node\nArgument: the absolute path to dex-mcp.mjs\nYour MCP client starts and stops the server.\nAsk your MCP client to run dex_create_pairing. Paste the code into Dex MCP in Roblox.\nInspect starts enabled. Edit and Run code are separate permissions.\nRun code uses your executor permissions.\n');
console.error('Built dist/dex-mcp.mjs');
